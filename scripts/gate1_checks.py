"""Gate 1 controls: position bias and visibility, per model x experiment x layout.

    uv run python scripts/gate1_checks.py            # every model with a dev run
    -> reports/gate1_checks.md, reports/gate1_checks.csv

Position bias comes from IDENTICAL pairs only: with nothing to prefer, any pull
toward the first/left image is bias. Visibility is the area under the ROC curve
for telling changed pairs from identical pairs on the same/different question
(0.5 = cannot tell, 1 = always can). Intervals are 95% bootstrap intervals over
pairs.
"""
from __future__ import annotations

import sys

import numpy as np
import pandas as pd

from aesx import analysis
from aesx.manifest import ROOT, read_manifest
from aesx.stats import bootstrap_ci

SPLIT = "dev"
LAYOUT_NAMES = {"two": "two images", "sbs": "side by side"}


def pair_meta() -> pd.DataFrame:
    rows = []
    for man in sorted((ROOT / "stimuli").glob(f"*/{SPLIT}/pairs.jsonl")):
        for p in read_manifest(man):
            rows.append({"pair_id": p.pair_id, "kind": p.kind, "condition": p.condition, "dose": p.dose, "cluster": p.cluster})
    return pd.DataFrame(rows)


def fmt(est: float, lo: float, hi: float, d: int = 2) -> str:
    return f"{est:.{d}f} [{lo:.{d}f}, {hi:.{d}f}]"


def main() -> int:
    meta = pair_meta()
    out_rows = []
    for run in sorted((ROOT / "runs" / SPLIT).glob("*/results.jsonl")):
        model = run.parent.name
        df = analysis.load_results(run)
        pp = analysis.prefer_by_pair(df).merge(meta, on="pair_id")
        sd = analysis.samediff_by_pair(df).merge(meta, on="pair_id")
        raw = df[df.task == "prefer"].merge(meta, on="pair_id")
        for (exp, layout), g in pp.groupby(["experiment", "layout"], sort=False):
            ident = g[g.kind == "identical"]
            manip = g[g.kind == "manipulation"]
            r = raw[(raw.experiment == exp) & (raw.layout == layout)]
            s = sd[(sd.experiment == exp) & (sd.layout == layout)]
            pos = bootstrap_ci(ident.pos_bias.values) if len(ident) else (np.nan,) * 3
            # each identical pair contributes its share of trials choosing the first image
            p_first_ident = bootstrap_ci(ident.p_first_hard.values) if len(ident) else (np.nan,) * 3
            p_first_all = float((r.lo_first > 0).mean())
            label = bootstrap_ci(g.label_bias.values)
            vis = analysis.auc_ci(s[s.kind == "manipulation"]["diff"].values, s[s.kind == "identical"]["diff"].values)
            hit = float((s[s.kind == "manipulation"]["diff"] > 0).mean())
            fa = float((s[s.kind == "identical"]["diff"] > 0).mean())
            # how much preference signal survives: spread of the bias-cancelled preference vs the bias itself
            out_rows.append({
                "model": model, "experiment": exp, "layout": layout,
                "n_identical": len(ident), "n_changed": len(manip),
                "pos_bias_logodds": pos[0], "pos_bias_lo": pos[1], "pos_bias_hi": pos[2],
                "p_first_identical": p_first_ident[0], "p_first_identical_lo": p_first_ident[1], "p_first_identical_hi": p_first_ident[2],
                "p_first_all_trials": p_first_all,
                "label_bias_logodds_A": label[0],
                "pref_sd_changed": float(manip.pref.std()),
                "visibility_auc": vis[0], "visibility_lo": vis[1], "visibility_hi": vis[2],
                "says_different_changed": hit, "says_different_identical": fa,
                "off_menu_rate": float(r.off_menu.mean()),  # preference trials in this layout
            })
    if not out_rows:
        print("no dev runs found")
        return 1
    t = pd.DataFrame(out_rows)
    (ROOT / "reports").mkdir(exist_ok=True)
    t.to_csv(ROOT / "reports" / "gate1_checks.csv", index=False, float_format="%.4f")

    lines = ["# Gate 1 checks: position bias and visibility (dev stimuli)", "",
             "Generated by `uv run python scripts/gate1_checks.py`. Intervals are 95% bootstrap over pairs.", "",
             "- **Position bias** (identical pairs only): log-odds of naming the first/left image; 0 = none. "
             "`P(first)` is the share of identical-pair trials on which the first/left image was named; 0.50 = none.",
             "- **Label bias**: log-odds toward the letter A regardless of what it names.",
             "- **Preference spread**: SD across changed pairs of the bias-cancelled preference (log-odds). "
             "Compare it with the position bias: if the bias is many times larger, raw choices are all bias.",
             "- **Visibility**: AUC for telling changed pairs from identical pairs on the same/different question. "
             "`says different` gives the rate of answering *different* for changed / for identical pairs "
             "(a model can say *different* to everything and still have a high AUC, if it says it more firmly for changed pairs).",
             "- **Off-menu**: share of preference trials in which the two permitted letters hold under half the "
             "next-token probability (the local-model analogue of a refusal; the brief's limit is 0.20).", ""]
    for model, g in t.groupby("model", sort=False):
        lines += [f"## {model}", "",
                  "| Experiment | Layout | Position bias (log-odds) | P(first), identical pairs | P(first), all trials | Label bias | Preference spread | Visibility AUC | Says different: changed / identical | Off-menu |",
                  "|---|---|---|---|---|---|---|---|---|---|"]
        for _, r in g.iterrows():
            lines.append(
                f"| {r.experiment} | {LAYOUT_NAMES[r.layout]} | {fmt(r.pos_bias_logodds, r.pos_bias_lo, r.pos_bias_hi)} | "
                f"{fmt(r.p_first_identical, r.p_first_identical_lo, r.p_first_identical_hi)} | {r.p_first_all_trials:.2f} | "
                f"{r.label_bias_logodds_A:+.2f} | {r.pref_sd_changed:.2f} | "
                f"{fmt(r.visibility_auc, r.visibility_lo, r.visibility_hi)} | "
                f"{r.says_different_changed:.2f} / {r.says_different_identical:.2f} | {r.off_menu_rate:.3f} |")
        lines.append("")
    (ROOT / "reports" / "gate1_checks.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
